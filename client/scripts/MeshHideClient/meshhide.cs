function MeshHide_apply() {
    if (isObject(ServerConnection)) {
        for (%i = 0; %i < ServerConnection.getCount(); %i++) {
            %o = ServerConnection.getObject(%i);
            if (!isObject(%o)) { continue; }
            if (!%o.isMemberOfClass("Player")) { continue; }
            if (!%o.isMethod("setMeshForceHidden")) {
                if (!$MeshHide::warned) { $MeshHide::warned = 1; echo("[MeshHide] Player has no setMeshForceHidden method"); }
                continue;
            }
            for (%j = 0; %j < $MeshHide::count; %j++) {
                %o.setMeshForceHidden($MeshHide::name[%j], true);
            }
        }
    }
    $MeshHide::ev = schedule(1500, 0, "MeshHide_apply");
}

function MeshHide_start() {
    cancel($MeshHide::ev);
    MeshHide_apply();
    echo("[MeshHide] started, hiding " @ $MeshHide::count @ " MMO-only meshes");
}
schedule(3000, 0, "MeshHide_start");